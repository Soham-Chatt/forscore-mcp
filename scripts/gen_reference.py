"""Generate docs/reference.md from the MCP server and CLI definitions (the single source).

uv run python scripts/gen_reference.py           # write docs/reference.md
uv run python scripts/gen_reference.py --check   # fail if it is out of date (CI)
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from pathlib import Path
from typing import Any

from forscore_mcp.cli import _parser
from forscore_mcp.server import server

OUTPUT = Path(__file__).parent.parent / "docs" / "reference.md"


def _type(schema: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in schema:
        target = defs[schema["$ref"].rsplit("/", 1)[-1]]
        return " \\| ".join(f'`"{v}"`' for v in target.get("enum", [])) or target.get("title", "")
    if "anyOf" in schema:
        options = [_type(s, defs) for s in schema["anyOf"] if s.get("type") != "null"]
        nullable = any(s.get("type") == "null" for s in schema["anyOf"])
        return " \\| ".join(options) + (" \\| null" if nullable else "")
    if "enum" in schema:
        return " \\| ".join(f'`"{v}"`' for v in schema["enum"])
    if schema.get("type") == "array":
        return f"list of {_type(schema.get('items', {}), defs)}"
    return schema.get("type", "any")


def _one_line(text: str) -> str:
    return " ".join(text.split())


def mcp_section() -> list[str]:
    lines = ["## MCP tools", ""]
    tools = asyncio.run(server.list_tools())
    for tool in sorted(tools, key=lambda t: t.name):
        data = tool.model_dump(exclude_none=True, by_alias=True)
        hints = data.get("annotations", {})
        effect = "read-only" if hints.get("readOnlyHint") else "writes (needs `confirm=true`)"
        lines += [
            f"### `{tool.name}`",
            "",
            f"*{effect}*",
            "",
            _one_line(tool.description or ""),
            "",
        ]
        schema = data["inputSchema"]
        props, required = schema.get("properties", {}), set(schema.get("required", []))
        if props:
            lines += ["| Parameter | Type | Default |", "|---|---|---|"]
            for name, prop in props.items():
                default = "required" if name in required else f"`{json.dumps(prop.get('default'))}`"
                lines.append(f"| `{name}` | {_type(prop, schema.get('$defs', {}))} | {default} |")
            lines.append("")
    lines += ["## MCP resources", ""]
    for resource in asyncio.run(server.list_resources()):
        lines.append(f"- `{resource.uri}`: {_one_line(resource.description or '')}")
    return [*lines, ""]


def _usage(action: argparse.Action) -> str:
    if action.option_strings:
        return f"[{action.option_strings[-1]}]"
    return f"[<{action.dest}>]" if action.nargs == "?" else f"<{action.dest}>"


def cli_section() -> list[str]:
    lines = ["## Command line", "", "`forscore-mcp` with no command runs the MCP server.", ""]
    parser = _parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {choice.dest: choice.help for choice in sub._choices_actions}
    for name, command in sub.choices.items():
        args = [a for a in command._actions if a.dest not in ("help", "json")]
        usage = " ".join(_usage(a) for a in args)
        lines += [f"### `{' '.join(filter(None, ['forscore-mcp', name, usage]))}`", ""]
        lines += [_one_line(helps.get(name) or ""), ""]
        documented = [a for a in args if a.help]
        if documented:
            lines += [f"- `{a.option_strings[-1] if a.option_strings else f'<{a.dest}>'}`: {a.help}"
                      for a in documented]  # fmt: skip
            lines.append("")
    lines += ["All commands except `serve` accept `--json` for machine-readable output.", ""]
    return lines


def render() -> str:
    header = [
        "# Reference",
        "",
        "<!-- Generated by scripts/gen_reference.py from the code. Do not edit by hand. -->",
        "",
    ]
    return "\n".join([*header, *mcp_section(), *cli_section()]).rstrip() + "\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print(f"{OUTPUT} is out of date; run: uv run python scripts/gen_reference.py")
            return 1
        return 0
    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
